// ---------- predicted news impact ----------

// Typical size of the move around a release, from the pair's own 1H
// average range: top-tier (NFP, CPI, rate decisions) ~1.5-3x ATR, other
// high-impact releases ~0.8-1.5x. A rough guide, not a forecast.
function expectedMove(event, atr, price, isTopTier) {
  if (!atr) return null;
  const [lo, hi] = isTopTier(event) ? [1.5, 3] : [0.8, 1.5];
  const gold = price >= 100;
  const unit = gold ? 1 : 0.0001; // $ for gold, pips for forex
  const a = Math.round((lo * atr) / unit), b = Math.round((hi * atr) / unit);
  return gold ? `$${a}–${b}` : `${a}–${b} pips`;
}

const LEVELS = { high: "HIGH", medium: "MEDIUM", low: "LOW", none: "NONE" };

// "📰 Predicted news impact" for an AI signal -- only when news is actually
// in play (a release ahead or just out, or the AI rated news as mattering).
exports.newsImpactSection = ({ analysis, newsCtx, atr, price, isTopTier }) => {
  const ni = analysis?.newsImpact && typeof analysis.newsImpact === "object" ? analysis.newsImpact : null;
  const aiLevel = ni && LEVELS[String(ni.level || "").toLowerCase()];
  const ahead = newsCtx?.upcoming || [];
  const reacted = newsCtx?.reactions || [];
  if (!ahead.length && !reacted.length && (!aiLevel || aiLevel === "NONE")) return "";
  const lines = [];
  if (aiLevel) lines.push(`• Impact rating (AI): ${aiLevel}${ni.bias ? ` — ${ni.bias} for this pair` : ""}${ni.reason ? ` (${ni.reason})` : ""}`);
  for (const e of ahead.slice(0, 2)) {
    const mv = expectedMove(e, atr, price, isTopTier);
    lines.push(`• ${e.currency} ${e.title} at ${e.time.toISOString().slice(11, 16)} UTC: ${isTopTier(e) ? "top-tier" : "high-impact"}${mv ? `, typical reaction ±${mv}` : ""}${e.forecast ? ` · forecast ${e.forecast}` : ""}${e.previous ? ` · previous ${e.previous}` : ""}`);
  }
  for (const r of reacted.slice(0, 2)) {
    lines.push(`• Already priced in: ${r.event.currency} ${r.event.title} moved ${price >= 100 ? `$${Math.abs(r.move).toFixed(1)}` : `${Math.abs(r.move / 0.0001).toFixed(0)} pips`} (${r.size || "measured"} ${r.event.currency} ${r.ccyStronger ? "buying" : "selling"})`);
  }
  return `\n\n📰 Predicted news impact\n${lines.join("\n")}`;
};

// For News Impact alerts: rating from the headline analysis + typical move.
exports.newsAlertImpact = ({ level, bias, atr, price }) => {
  const L = LEVELS[String(level || "").toLowerCase()] || String(level || "").toUpperCase();
  const gold = price >= 100;
  const mv = atr ? (gold ? `$${Math.round(0.8 * atr)}–${Math.round(2 * atr)}` : `${Math.round((0.8 * atr) / 0.0001)}–${Math.round((2 * atr) / 0.0001)} pips`) : null;
  return `\n\n📰 Predicted news impact\n• Impact rating (AI): ${L}${bias ? ` — ${bias} for this pair` : ""}${mv ? `\n• Typical reaction to a headline like this: ±${mv} (from the pair's 1H average range)` : ""}`;
};
