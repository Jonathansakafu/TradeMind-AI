// "📌 Signal basis" section appended to every signal's notes (added
// 2026-10 at the user's request): where the signal really came from (AI
// analysis of market data and by which AI, a news headline, the user's own
// TradingView alert, past trades, books...) and the technical reasons
// behind it (timeframes, BOS / CHoCH, liquidity, levels). Shown in the app,
// push and email.

const fmtFor = (ref) => (n) => Number(n).toFixed(ref >= 100 ? 2 : 5);

function tfLine(read, fmt) {
  if (!read || read.trend === "unknown") return null;
  const bits = [`${read.label} ${read.trend}`];
  if (read.major?.trend && read.major.trend !== "unknown") bits.push(`major structure ${read.major.trend}`);
  const e = read.major?.lastEvent || read.internal?.lastEvent;
  if (e && e.ago <= 30) bits.push(`last ${e.dir} ${e.type} at ${fmt(e.level)} (${e.ago} candles ago)`);
  return bits.join(", ");
}

function liquidityLine(ctx, fmt) {
  const out = [];
  for (const read of [ctx?.h4, ctx?.h1, ctx?.m15]) {
    if (!read?.liquidity) continue;
    for (const sw of read.liquidity.sweeps) out.push(`${read.label} sweep of ${sw.side} at ${fmt(sw.level)} (${sw.dir})`);
    if (read.liquidity.equalHighs) out.push(`${read.label} equal highs at ${fmt(read.liquidity.equalHighs)} above`);
    if (read.liquidity.equalLows) out.push(`${read.label} equal lows at ${fmt(read.liquidity.equalLows)} below`);
  }
  return out.slice(0, 4).join(" · ") || null;
}

// AI market-analysis signal (the main forex/gold pipeline).
exports.forAiSignal = ({ analysis, ctx, newsCtx, inputs, price }) => {
  const fmt = fmtFor(price || 1);
  const used = [];
  if (inputs.structure) used.push("market structure (4H / 1H / 15m)");
  if (inputs.books) used.push("your uploaded books");
  if (inputs.screenshots) used.push("your chart screenshots");
  if (inputs.pastTrades) used.push(`${inputs.pastTrades} of your past trades`);
  if (inputs.trackRecord) used.push("this pair's signal track record");
  if (inputs.learned) used.push("self-learning notes from your results");
  if (inputs.news) used.push(`${inputs.news} news headline${inputs.news === 1 ? "" : "s"}`);
  if (inputs.momentum) used.push("momentum / RSI");
  if (newsCtx?.text) used.push("economic calendar");

  const lines = [
    `• Source: AI analysis of live market data${analysis.provider ? ` by ${analysis.provider}` : ""}${analysis.verified === true ? ", double-checked by a second AI pass" : ""}`,
  ];
  if (analysis.primarySource) lines.push(`• Main driver (AI's own view): ${analysis.primarySource}`);
  if (used.length) lines.push(`• Given to the AI: ${used.join(" · ")}`);
  const basis = (analysis.basis || []).filter((b) => typeof b === "string" && b.trim()).slice(0, 6);
  if (basis.length) lines.push(`• Technical reasons (AI): ${basis.join("; ")}`);
  const tfs = [ctx?.h4, ctx?.h1, ctx?.m15].map((r) => tfLine(r, fmt)).filter(Boolean);
  if (tfs.length) lines.push(`• Timeframes: ${tfs.join(" | ")}`);
  const liq = liquidityLine(ctx, fmt);
  if (liq) lines.push(`• Liquidity: ${liq}`);
  for (const e of (newsCtx?.upcoming || []).slice(0, 2)) {
    const mins = Math.round((e.time - Date.now()) / 60000);
    lines.push(`• News ahead: ${e.currency} ${e.title} at ${e.time.toISOString().slice(11, 16)} UTC (in ${mins >= 60 ? `${Math.floor(mins / 60)}h ${mins % 60}m` : `${mins} min`})${e.forecast ? `, forecast ${e.forecast}` : ""}${e.previous ? `, previous ${e.previous}` : ""}`);
  }
  for (const r of (newsCtx?.reactions || []).slice(0, 2)) lines.push(`• News reaction: ${r.line}`);
  return `\n\n📌 Signal basis\n${lines.join("\n")}`;
};

